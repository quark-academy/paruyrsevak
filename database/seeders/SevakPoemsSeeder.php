/**
 * The poems that were added from the editor's list (no recordings yet).
 *
 * Deploy: php artisan db:seed --class=SevakPoemsSeeder --force
 *
 * Every poem arrives with its text, SEO meta and the split word list, so the
 * only thing left in the admin panel is generating the voice with timings
 * ("Համաժամեցնել ElevenLabs-ից" on the timings page).
 *
 * Poems are matched by title: an existing one is never overwritten (that
 * would break its word timings), so re-running the seeder is safe.
 */
class SevakPoemsSeeder extends Seeder

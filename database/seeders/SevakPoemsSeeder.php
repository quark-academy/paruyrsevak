    public function run(): void
    {
        $synchronizer = app(PoemWordSynchronizer::class);

        foreach ($this->poems() as $data) {
            $poem = Poem::query()->firstOrCreate(
                ['title' => $data['title']],
                [
                    'content' => $data['content'],
                    'is_original' => false,
                    'meta_title' => $data['meta_title'],
                    'meta_description' => $data['meta_description'],
                ],
            );

            if ($poem->words()->count() === 0) {
                $synchronizer->syncFromContent($poem);
            }

            $state = $poem->wasRecentlyCreated ? 'created' : 'already there';

            $this->command?->info("Poem {$state}: {$poem->slug} (".$poem->words()->count().' words)');
        }
    }

